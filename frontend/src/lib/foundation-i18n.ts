export function foundationText(locale: string, text: string): string {
  if (locale !== "fa") return text;
  const workflow = workflowText(locale, text);
  if (workflow !== text) return workflow;
  const length = text.match(/^Use at most (\d+) characters\.$/);
  return dari[text] ?? (length ? `حداکثر ${length[1]} حرف وارد کنید.` : text);
}
